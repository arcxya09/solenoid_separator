import sys, re
s = open('report_ex2.html').read()

def R(old, new, n=1):
    global s
    if s.count(old) != n:
        sys.exit(f'count {s.count(old)}: ' + old[:80])
    s = s.replace(old, new)

# 第 05 节小节按出现顺序编号
for a, b in [('<h3>10. v3 修订', '<h3>5. v3 修订'), ('<h3>5. 中性铷', '<h3>6. 中性铷'), ('<h3>6. 电极支撑', '<h3>7. 电极支撑'),
             ('<h3>7. 寿命', '<h3>8. 寿命'), ('<h3>8. 电源', '<h3>9. 电源'), ('<h3>11. 外部专家', '<h3>10. 外部专家'),
             ('<h3>9. 修订版的整机复核', '<h3>11. v2 修订版的整机复核')]:
    R(a, b)

# 第 11 节：方式 B 两块移到方式 C 之后；离心势垒一条放回方式 B 的第一张列表
i = s.index('  <h3>方式 B：增大环半径'); j = s.index('  <h3>方式 A：放大几何</h3>')
B = s[i:j]; s = s[:i] + s[j:]
k = s.index('  <h3>离子源放大</h3>')
s = s[:k] + B + s[k:]
li = re.search(r'\s*<li><b>离心势垒（专家另一条意见）：</b>.*?</li>', s, re.S).group(0)
s = s.replace(li, '', 1)
R('<li><b>本报告其余各节</b>', li.strip() + '\n    <li><b>本报告其余各节</b>')
R('下表是两种保持过轴次数不变的放大方式；减少过轴次数的方式 B 见表后：', '下表是两种保持过轴次数不变的放大方式（A、C）；减少过轴次数的方式 B 放在方式 C 之后：')

